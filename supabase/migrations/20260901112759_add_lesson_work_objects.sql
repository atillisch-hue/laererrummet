create policy "assigned staff read lesson instances"
on public.lesson_instances
for select
to authenticated
using (
  public.has_school_role(school_id, 'admin')
  or exists (
    select 1 from public.schedule_teachers st
    where st.schedule_entry_id = lesson_instances.schedule_entry_id
      and st.teacher_id = (select auth.uid())
  )
  or exists (
    select 1 from public.substitute_assignments sa
    where sa.schedule_entry_id = lesson_instances.schedule_entry_id
      and sa.assignment_date = lesson_instances.lesson_date
      and sa.substitute_teacher_id = (select auth.uid())
  )
);

