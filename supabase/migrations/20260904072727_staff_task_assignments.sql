grant execute on function private.create_staff_task_internal(text,text,date,uuid[]) to authenticated;
grant execute on function private.delete_staff_task_internal(bigint) to authenticated;
revoke all on function public.admin_create_staff_task(text,text,date,uuid[]) from public,anon;
