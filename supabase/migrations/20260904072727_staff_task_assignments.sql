create table if not exists public.staff_tasks (
  id bigint generated by default as identity primary key,
  school_id bigint not null references public.schools(id) on delete cascade,
  title text not null check (length(trim(title)) between 1 and 240),
  description text null,
  due_date date null,
  created_by uuid not null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.staff_task_assignees (
  task_id bigint not null references public.staff_tasks(id) on delete cascade,
  user_id uuid not null,
  completed boolean not null default false,
  completed_at timestamptz null,
  created_at timestamptz not null default now(),
  primary key (task_id,user_id)
);

create index if not exists staff_tasks_school_due_idx on public.staff_tasks(school_id,due_date,id);
create index if not exists staff_task_assignees_user_idx on public.staff_task_assignees(user_id,completed,task_id);

alter table public.staff_tasks enable row level security;
alter table public.staff_task_assignees enable row level security;

create or replace function private.is_staff_task_assignee(p_task_id bigint,p_user_id uuid)
returns boolean
language sql
stable
security definer
set search_path=public,private
as $$
  select exists(
    select 1 from public.staff_task_assignees a
    where a.task_id=p_task_id and a.user_id=p_user_id
  );
$$;

create or replace function private.staff_task_school_id(p_task_id bigint)
returns bigint
language sql
stable
security definer
set search_path=public,private
as $$
  select t.school_id from public.staff_tasks t where t.id=p_task_id;
$$;

revoke all on function private.is_staff_task_assignee(bigint,uuid) from public,anon;
revoke all on function private.staff_task_school_id(bigint) from public,anon;
grant execute on function private.is_staff_task_assignee(bigint,uuid) to authenticated;
grant execute on function private.staff_task_school_id(bigint) to authenticated;

create policy staff_tasks_read on public.staff_tasks
for select to authenticated
using (
  public.has_school_role(school_id,'admin')
  or public.has_school_role(school_id,'leader')
  or private.is_staff_task_assignee(id,auth.uid())
);

create policy staff_task_assignees_read on public.staff_task_assignees
for select to authenticated
using (
  user_id=auth.uid()
  or public.has_school_role(private.staff_task_school_id(task_id),'admin')
  or public.has_school_role(private.staff_task_school_id(task_id),'leader')
);

revoke all on public.staff_tasks from anon;
revoke all on public.staff_task_assignees from anon;
grant select on public.staff_tasks to authenticated;
grant select on public.staff_task_assignees to authenticated;

create or replace function private.create_staff_task_internal(
  p_title text,
  p_description text,
  p_due_date date,
  p_user_ids uuid[]
)
returns bigint
language plpgsql
security definer
set search_path=public,private
as $$
declare
  v_school_id bigint;
  v_task_id bigint;
  v_user_ids uuid[];
begin
  if auth.uid() is null then raise exception 'Authentication required'; end if;
  if length(trim(coalesce(p_title,'')))=0 then raise exception 'Title required'; end if;

  select sm.school_id into v_school_id
  from public.school_memberships sm
  where sm.user_id=auth.uid() and sm.active=true and sm.role in ('admin','leader')
  order by sm.school_id
  limit 1;
  if v_school_id is null then raise exception 'Admin role required'; end if;

  select array_agg(distinct x) into v_user_ids
  from unnest(coalesce(p_user_ids,'{}'::uuid[])) x
  where x is not null;
  if coalesce(cardinality(v_user_ids),0)=0 then raise exception 'Choose at least one staff member'; end if;

  if exists(
    select 1 from unnest(v_user_ids) u
    where not exists(
      select 1 from public.school_memberships sm
      where sm.school_id=v_school_id and sm.user_id=u and sm.active=true
        and sm.role in ('teacher','admin','leader')
    )
  ) then raise exception 'All assignees must be active staff at the same school'; end if;

  insert into public.staff_tasks(school_id,title,description,due_date,created_by)
  values(v_school_id,trim(p_title),nullif(trim(coalesce(p_description,'')),''),p_due_date,auth.uid())
  returning id into v_task_id;

  insert into public.staff_task_assignees(task_id,user_id)
  select v_task_id,u from unnest(v_user_ids) u;

  return v_task_id;
end;
$$;

create or replace function public.admin_create_staff_task(
  p_title text,
  p_description text default null,
  p_due_date date default null,
  p_user_ids uuid[] default '{}'
)
returns bigint
language sql
security invoker
set search_path=public,private
as $$
  select private.create_staff_task_internal(p_title,p_description,p_due_date,p_user_ids);
$$;

create or replace function private.delete_staff_task_internal(p_task_id bigint)
returns void
language plpgsql
security definer
set search_path=public,private
as $$
declare v_rows integer;
begin
  if auth.uid() is null then raise exception 'Authentication required'; end if;
  delete from public.staff_tasks t
  where t.id=p_task_id
    and (public.has_school_role(t.school_id,'admin') or public.has_school_role(t.school_id,'leader'));
  get diagnostics v_rows=row_count;
  if v_rows<>1 then raise exception 'Task not found or access denied'; end if;
end;
$$;

create or replace function public.admin_delete_staff_task(p_task_id bigint)
returns void
language sql
security invoker
set search_path=public,private
as $$
  select private.delete_staff_task_internal(p_task_id);
$$;

revoke all on function private.create_staff_task_internal(text,text,date,uuid[]) from public,anon;
