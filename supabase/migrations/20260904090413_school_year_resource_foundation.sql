with work_year as (
  select school_id,school_year,min(period_start) as period_start,max(period_end) as period_end,
         row_number() over(partition by school_id order by max(period_end) desc) as rn
  from public.staff_work_profiles
  group by school_id,school_year
), source as (
  select s.id as school_id,
         coalesce(w.school_year,
           case when ss.school_year_start is not null then extract(year from ss.school_year_start)::int::text||'/'||(extract(year from ss.school_year_start)::int+1)::text end,
           extract(year from current_date)::int::text||'/'||(extract(year from current_date)::int+1)::text) as label,
         coalesce(w.period_start,ss.school_year_start,make_date(extract(year from current_date)::int,8,1)) as period_start,
         coalesce(w.period_end,ss.school_year_end,make_date(extract(year from current_date)::int+1,7,31)) as period_end,
         ss.school_year_start as teaching_start,
         ss.school_year_end as teaching_end
  from public.schools s
  left join work_year w on w.school_id=s.id and w.rn=1
  left join public.school_settings ss on ss.school_id=s.id
)
insert into public.school_years(school_id,label,period_start,period_end,teaching_start,teaching_end,status)
select school_id,label,period_start,period_end,
       case when teaching_start between period_start and period_end then teaching_start end,
       case when teaching_end between period_start and period_end then teaching_end end,
       'active'
from source
where period_end>=period_start
on conflict (school_id,label) do update
set period_start=excluded.period_start,
    period_end=excluded.period_end,
    teaching_start=excluded.teaching_start,
    teaching_end=excluded.teaching_end,
    status='active',
    updated_at=now();

