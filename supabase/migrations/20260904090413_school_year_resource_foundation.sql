create table if not exists public.school_years (
  id bigint generated by default as identity primary key,
  school_id bigint not null references public.schools(id) on delete cascade,
  label text not null,
  period_start date not null,
  period_end date not null,
  teaching_start date,
  teaching_end date,
  status text not null default 'draft' check (status in ('draft','active','archived')),
  created_by uuid references auth.users(id) on delete set null default auth.uid(),
  updated_by uuid references auth.users(id) on delete set null default auth.uid(),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint school_years_school_label_key unique (school_id,label),
  constraint school_years_period_check check (period_end >= period_start),
  constraint school_years_teaching_range_check check (
    (teaching_start is null and teaching_end is null)
    or (
      teaching_start is not null and teaching_end is not null
      and teaching_end >= teaching_start
      and teaching_start >= period_start
      and teaching_end <= period_end
    )
  )
);
create unique index if not exists school_years_one_active_per_school_idx
  on public.school_years(school_id) where status='active';
create index if not exists school_years_school_period_idx on public.school_years(school_id,period_start,period_end);
create index if not exists school_years_created_by_idx on public.school_years(created_by);
create index if not exists school_years_updated_by_idx on public.school_years(updated_by);

