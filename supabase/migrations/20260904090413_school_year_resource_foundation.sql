create or replace function public.save_school_year_calendar(
  p_school_id bigint,
  p_teaching_start date,
  p_teaching_end date,
  p_closed_days jsonb,
  p_calendar_events jsonb
) returns void
language plpgsql
security invoker
set search_path=''
as $$
declare
  v_year_id bigint;
  v_item jsonb;
  v_date date;
  v_kind text;
begin
  if not (public.has_school_role(p_school_id,'admin') or public.has_school_role(p_school_id,'leader')) then
    raise exception 'Leadership access required';
  end if;
  if p_teaching_start is null or p_teaching_end is null or p_teaching_end < p_teaching_start then
    raise exception 'Invalid teaching period';
  end if;
  if jsonb_typeof(coalesce(p_closed_days,'[]'::jsonb)) <> 'array'
     or jsonb_typeof(coalesce(p_calendar_events,'[]'::jsonb)) <> 'array' then
    raise exception 'Calendar payload must be arrays';
  end if;

  select id into v_year_id
  from public.school_years
  where school_id=p_school_id and status='active'
  limit 1;
  if v_year_id is null then raise exception 'Active school year not found'; end if;

  update public.school_years
  set teaching_start=p_teaching_start, teaching_end=p_teaching_end,
      updated_by=(select auth.uid()), updated_at=now()
  where id=v_year_id
    and p_teaching_start>=period_start and p_teaching_end<=period_end;
  if not found then raise exception 'Teaching period must be inside the school-year resource period'; end if;

  insert into public.school_settings(school_id,school_year_start,school_year_end,closed_days,calendar_events,updated_by,updated_at)
  values(p_school_id,p_teaching_start,p_teaching_end,coalesce(p_closed_days,'[]'::jsonb),coalesce(p_calendar_events,'[]'::jsonb),(select auth.uid()),now())
  on conflict (school_id) do update
  set school_year_start=excluded.school_year_start,
      school_year_end=excluded.school_year_end,
      closed_days=excluded.closed_days,
      calendar_events=excluded.calendar_events,
      updated_by=excluded.updated_by,
      updated_at=excluded.updated_at;

  delete from public.school_year_calendar_events
  where school_year_id=v_year_id and source='school_calendar';

  for v_item in select value from jsonb_array_elements(coalesce(p_closed_days,'[]'::jsonb)) loop
    v_date=(v_item->>'date')::date;
    insert into public.school_year_calendar_events(school_year_id,starts_on,ends_on,title,event_kind,closes_school,visibility,source,created_by,updated_by)
    values(v_year_id,v_date,v_date,coalesce(nullif(trim(v_item->>'label'),''),'Lukkedag'),'closure',true,'all','school_calendar',(select auth.uid()),(select auth.uid()));
  end loop;

  for v_item in select value from jsonb_array_elements(coalesce(p_calendar_events,'[]'::jsonb)) loop
    v_date=(v_item->>'date')::date;
    v_kind=case when v_item->>'kind' in ('pedagogical','special_week','project','trip','event','other') then v_item->>'kind' else 'other' end;
    insert into public.school_year_calendar_events(school_year_id,starts_on,ends_on,title,event_kind,closes_school,visibility,source,created_by,updated_by)
    values(v_year_id,v_date,v_date,coalesce(nullif(trim(v_item->>'label'),''),'Begivenhed'),v_kind,false,'staff','school_calendar',(select auth.uid()),(select auth.uid()));
  end loop;
end;
$$;
revoke all on function public.save_school_year_calendar(bigint,date,date,jsonb,jsonb) from public,anon;
grant execute on function public.save_school_year_calendar(bigint,date,date,jsonb,jsonb) to authenticated;

create or replace function public.publish_schedule_version(p_version_id bigint,p_effective_from date default null)
returns void
language plpgsql
security invoker
set search_path=''
as $$
declare
  v_year_id bigint;
  v_school_id bigint;
  v_start date;
begin
  select sv.school_year_id,sy.school_id,coalesce(p_effective_from,sy.teaching_start,sy.period_start)
  into v_year_id,v_school_id,v_start
  from public.school_schedule_versions sv
  join public.school_years sy on sy.id=sv.school_year_id
  where sv.id=p_version_id;
  if v_year_id is null then raise exception 'Schedule version not found'; end if;
  if not (public.has_school_role(v_school_id,'admin') or public.has_school_role(v_school_id,'leader')) then
    raise exception 'Leadership access required';
  end if;

  update public.school_schedule_versions
  set status='archived', effective_to=v_start-1, updated_by=(select auth.uid()), updated_at=now()
  where school_year_id=v_year_id and status='published' and id<>p_version_id;

  update public.school_schedule_versions
  set status='published', effective_from=v_start, effective_to=null,
      published_at=now(), published_by=(select auth.uid()), updated_by=(select auth.uid()), updated_at=now()
  where id=p_version_id;
end;
$$;
revoke all on function public.publish_schedule_version(bigint,date) from public,anon;
grant execute on function public.publish_schedule_version(bigint,date) to authenticated;