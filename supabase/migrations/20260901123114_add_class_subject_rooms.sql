create policy "school staff read subjects" on public.subjects for select to authenticated using (public.is_school_staff(school_id));
create policy "school staff create subjects" on public.subjects for insert to authenticated with check (public.is_school_staff(school_id) and created_by=(select auth.uid()));
create policy "school admins update subjects" on public.subjects for update to authenticated using (public.has_school_role(school_id,'admin')) with check (public.has_school_role(school_id,'admin'));
create policy "school admins delete subjects" on public.subjects for delete to authenticated using (public.has_school_role(school_id,'admin'));

create policy "school staff read class subjects" on public.class_subjects for select to authenticated using (public.is_school_staff(school_id));
create policy "class teachers create class subjects" on public.class_subjects for insert to authenticated with check (
  public.has_school_role(school_id,'admin')
  or exists (
    select 1 from public.teacher_classes tc
    join public.school_memberships sm on sm.user_id=tc.teacher_id and sm.school_id=class_subjects.school_id and sm.role='teacher' and sm.active=true
    where tc.class_id=class_subjects.class_id and tc.teacher_id=(select auth.uid())
  )
);
create policy "subject teachers update class subjects" on public.class_subjects for update to authenticated using (public.can_edit_class_subject(id)) with check (public.can_edit_class_subject(id));
create policy "subject teachers delete class subjects" on public.class_subjects for delete to authenticated using (public.can_edit_class_subject(id));

create policy "school staff read subject teachers" on public.class_subject_teachers for select to authenticated using (
  exists(select 1 from public.class_subjects cs where cs.id=class_subject_id and public.is_school_staff(cs.school_id))
);
create policy "class teachers manage subject teachers" on public.class_subject_teachers for all to authenticated using (
  exists(
    select 1 from public.class_subjects cs
    where cs.id=class_subject_id and (
      public.has_school_role(cs.school_id,'admin')
      or exists(select 1 from public.teacher_classes tc where tc.class_id=cs.class_id and tc.teacher_id=(select auth.uid()))
    )
  )
) with check (
  exists(
    select 1 from public.class_subjects cs
    join public.school_memberships target on target.user_id=class_subject_teachers.user_id and target.school_id=cs.school_id and target.role='teacher' and target.active=true
    where cs.id=class_subject_id and (
      public.has_school_role(cs.school_id,'admin')
      or exists(select 1 from public.teacher_classes tc where tc.class_id=cs.class_id and tc.teacher_id=(select auth.uid()))
    )
  )
);

create policy "school staff read subject room items" on public.subject_room_items for select to authenticated using (
  exists(select 1 from public.class_subjects cs where cs.id=class_subject_id and public.is_school_staff(cs.school_id))
);
create policy "subject teachers create room items" on public.subject_room_items for insert to authenticated with check (public.can_edit_class_subject(class_subject_id));
create policy "subject teachers update room items" on public.subject_room_items for update to authenticated using (public.can_edit_class_subject(class_subject_id)) with check (public.can_edit_class_subject(class_subject_id));
create policy "subject teachers delete room items" on public.subject_room_items for delete to authenticated using (public.can_edit_class_subject(class_subject_id));

insert into public.subjects(school_id,name,slug,created_by)
select distinct c.school_id, trim(se.subject), regexp_replace(lower(trim(se.subject)),'[^a-z0-9æøå]+','-','g'), null::uuid
from public.schedule_entries se
join public.classes c on c.id=se.class_id
where c.school_id is not null
  and trim(se.subject)<>''
  and lower(trim(se.subject)) not in ('pause','samling')
on conflict (school_id,slug) do nothing;

insert into public.class_subjects(school_id,class_id,subject_id,title,created_by,updated_by)
select distinct c.school_id,se.class_id,s.id,s.name,null::uuid,null::uuid
from public.schedule_entries se
join public.classes c on c.id=se.class_id
join public.subjects s on s.school_id=c.school_id and s.slug=regexp_replace(lower(trim(se.subject)),'[^a-z0-9æøå]+','-','g')
where lower(trim(se.subject)) not in ('pause','samling')
on conflict (class_id,subject_id) do nothing;

insert into public.class_subject_teachers(class_subject_id,user_id)
select distinct cs.id,st.teacher_id
from public.schedule_entries se
join public.schedule_teachers st on st.schedule_entry_id=se.id
join public.classes c on c.id=se.class_id
join public.subjects s on s.school_id=c.school_id and s.slug=regexp_replace(lower(trim(se.subject)),'[^a-z0-9æøå]+','-','g')
join public.class_subjects cs on cs.class_id=se.class_id and cs.subject_id=s.id
join public.school_memberships sm on sm.user_id=st.teacher_id and sm.school_id=c.school_id and sm.role='teacher' and sm.active=true
where lower(trim(se.subject)) not in ('pause','samling')
on conflict do nothing;
